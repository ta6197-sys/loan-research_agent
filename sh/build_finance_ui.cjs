// 신뢰한 로컬 템플릿만 미리 컴파일한다. 브라우저에서는 eval/외부 CDN을 사용하지 않는다.
const fs=require('fs'),vm=require('vm'),path=require('path');
const root=path.resolve(__dirname,'..');
const sandbox={console};vm.createContext(sandbox);
vm.runInContext(fs.readFileSync(path.join(root,'static/vendor/vue.global.prod.js'),'utf8'),sandbox);
const template=fs.readFileSync(path.join(root,'static/finance-template.html'),'utf8');
const render=sandbox.Vue.compile(template,{hoistStatic:false,decodeEntities:raw=>raw.replace(/&(amp|lt|gt|quot|apos|nbsp);/g,(_,key)=>({amp:'&',lt:'<',gt:'>',quot:'\"',apos:"'",nbsp:' '})[key])}).toString();
fs.writeFileSync(path.join(root,'static/finance-render.js'),'// Generated by sh/build_finance_ui.cjs; trusted template only.\nwindow.FinanceRender=(()=>{const _Vue=Vue;return '+render+';})();\n');
